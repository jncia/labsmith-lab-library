/*
 * What the host must do beyond serving the built pages: send each stable
 * download address on to wherever the file is hosted, and mark every response
 * `noindex` while the site is not to be indexed.
 *
 * The site is a static export served by Cloudflare (wrangler.jsonc). In a
 * build, scripts/write-hosting-files.mts renders these rules into the
 * `_redirects` and `_headers` files Cloudflare reads from the output folder.
 * In `next dev`, next.config.ts hands the same rules to Next, so one list
 * drives both.
 *
 * This file is imported by Next and run directly by Node (type stripping), so
 * it imports only the catalog and indexing modules.
 */
import type { Catalog } from "./catalog.ts";

export type DownloadRedirect = { source: string; destination: string };

/**
 * A static export refuses a dynamic route with no pages, and a release catalog
 * can list no labs yet. Then /labs/[id] builds this one placeholder, which
 * renders "not found", and scripts/write-hosting-files.mts deletes its files,
 * so the address stays a plain 404.
 */
export const NO_LABS_PLACEHOLDER = "no-labs-listed";
export type HeaderRule = { source: string; headers: { key: string; value: string }[] };

/** Only hosted files get a route: a download address with no file behind it stays a 404. */
export function downloadRedirects(catalog: Catalog): DownloadRedirect[] {
  const routes: DownloadRedirect[] = [];
  if (catalog.client.url) routes.push({ source: "/download/client", destination: catalog.client.url });
  for (const lab of catalog.labs) {
    if (lab.release.status === "released" && lab.release.download) {
      routes.push({ source: `/download/labs/${lab.id}`, destination: lab.release.download.url });
    }
  }
  return routes;
}

/** While the site is not to be indexed, every response says so, files included. */
export function headerRules(indexable: boolean): HeaderRule[] {
  return indexable ? [] : [{ source: "/:path*", headers: [{ key: "X-Robots-Tag", value: "noindex, nofollow" }] }];
}

/** Cloudflare `_redirects`: temporary (302), so a file can move host without stale caches. */
export function renderRedirectsFile(routes: DownloadRedirect[]): string {
  const lines = routes.map((r) => `${r.source} ${r.destination} 302`);
  return ["# Generated by scripts/write-hosting-files.mts from the catalog. Do not edit.", ...lines, ""].join("\n");
}

/** Cloudflare `_headers`: Next's `/:path*` is written as Cloudflare's `/*`. */
export function renderHeadersFile(rules: HeaderRule[]): string {
  const blocks = rules.map((r) => {
    const source = r.source === "/:path*" ? "/*" : r.source;
    return [source, ...r.headers.map((h) => `  ${h.key}: ${h.value}`)].join("\n");
  });
  return ["# Generated by scripts/write-hosting-files.mts. Do not edit.", ...blocks, ""].join("\n");
}
